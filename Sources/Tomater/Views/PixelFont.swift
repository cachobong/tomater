/// Text drawn with the pixel font. `scale` is the size of one font pixel in points.
struct PixelText: View {
    let text: String
    var scale: CGFloat = 2
    var color: Color = Pal.text
    var shadow: Color? = nil

    init(_ text: String, scale: CGFloat = 2, color: Color = Pal.text, shadow: Color? = nil) {
        self.text = text
        self.scale = scale
        self.color = color
        self.shadow = shadow
    }

    var body: some View {
        let chars = Array(text.uppercased())
        let extra = shadow == nil ? 0 : scale
        let width = CGFloat(max(chars.count * PixelFont.advance - 1, 0)) * scale + extra
        let height = 7 * scale + extra

        Canvas { context, _ in
            var path = Path()
            for (index, char) in chars.enumerated() {
                guard let glyph = PixelFont.glyphs[char] else { continue }
                for (y, row) in glyph.enumerated() {
                    for (x, pixel) in row.enumerated() where pixel == "#" {
                        path.addRect(CGRect(
                            x: CGFloat(index * PixelFont.advance + x) * scale,
                            y: CGFloat(y) * scale,
                            width: scale, height: scale))
                    }
                }
            }
            if let shadow {
                context.fill(path.offsetBy(dx: scale, dy: scale), with: .color(shadow))
            }
            context.fill(path, with: .color(color))
        }
        .frame(width: width, height: height)
        .accessibilityElement()
        .accessibilityLabel(text)
    }
}
